package main

// Security helpers: end-to-end encryption between the two players, input
// validation and resource limits.
//
// Encryption: each side makes a fresh X25519 key pair per session. The joiner's
// hello and the host's reply carry the public keys; both derive an AES-256-GCM
// key with HKDF-SHA256 using the game code as salt. Everything after the
// handshake (ports, game traffic) is encrypted and authenticated, so the relay
// and anyone else listening on the channel can't read or inject game data.

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/ecdh"
	"crypto/hkdf"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"errors"
	"regexp"
)

const (
	maxItemData = 64 * 1024       // largest single packet we accept from the peer
	maxQueue    = 2 * 1024 * 1024 // outgoing bytes buffered before we start dropping
	maxTCPConns = 16              // simultaneous tunnelled TCP connections
	maxUDPFlows = 64              // simultaneous tunnelled UDP flows
	maxPorts    = 16              // ports a host may advertise
	maxEnvelope = 220 * 1024      // largest relay message we decrypt
)

var codeRe = regexp.MustCompile(`^[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$`)

// validCode checks the format of a game code (as generated by randCode).
func validCode(c string) bool { return codeRe.MatchString(c) }

type sessionKey struct {
	priv *ecdh.PrivateKey
	pub  string // base64
}

func newSessionKey() *sessionKey {
	k, err := ecdh.X25519().GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	return &sessionKey{priv: k, pub: base64.StdEncoding.EncodeToString(k.PublicKey().Bytes())}
}

func (s *sessionKey) derive(peerPub, code string) (cipher.AEAD, error) {
	b, err := base64.StdEncoding.DecodeString(peerPub)
	if err != nil {
		return nil, err
	}
	pk, err := ecdh.X25519().NewPublicKey(b)
	if err != nil {
		return nil, err
	}
	shared, err := s.priv.ECDH(pk)
	if err != nil {
		return nil, err
	}
	key, err := hkdf.Key(sha256.New, shared, []byte(code), "ptlink v1 session", 32)
	if err != nil {
		return nil, err
	}
	blk, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	return cipher.NewGCM(blk)
}

func seal(a cipher.AEAD, ad string, items []item) (string, error) {
	pt, err := json.Marshal(items)
	if err != nil {
		return "", err
	}
	nonce := make([]byte, a.NonceSize())
	rand.Read(nonce)
	return base64.StdEncoding.EncodeToString(a.Seal(nonce, nonce, pt, []byte(ad))), nil
}

func open(a cipher.AEAD, ad, x string) ([]item, error) {
	if len(x) > maxEnvelope {
		return nil, errors.New("too large")
	}
	b, err := base64.StdEncoding.DecodeString(x)
	if err != nil || len(b) < a.NonceSize() {
		return nil, errors.New("bad ciphertext")
	}
	pt, err := a.Open(nil, b[:a.NonceSize()], b[a.NonceSize():], []byte(ad))
	if err != nil {
		return nil, err
	}
	var items []item
	if err := json.Unmarshal(pt, &items); err != nil {
		return nil, err
	}
	return items, nil
}

func validPort(p int) bool { return p > 0 && p < 65536 }
